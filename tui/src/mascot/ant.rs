fn pose(grid: &Grid) -> Dots {
    parse_grid(grid)
}

/// Standing, antennae twitching, a crumb shuffle, one slow step; the last pose is the start.
fn idle_cycle() -> Vec<Dots> {
    [
        &STAND, &WIG, &STAND, &WIG, &STAND, &STAND, &CRUMB_UP, &STAND, &STAND, &STEP_A, &STAND,
        &STEP_B, &STAND, &STAND, &WIG, &STAND, &STAND, &STAND, &WIG, &STAND,
    ]
    .iter()
    .map(|g| pose(g))
    .collect()
}

/// Scurrying under the load: gait cycles, the body bobs, the crumb bounces.
fn work_cycle() -> Vec<Dots> {
    [
        &SCURRY_A, &SCURRY_C, &SCURRY_B, &STEP_A, &SCURRY_C, &SCURRY_B, &STEP_B, &SCURRY_A,
    ]
    .iter()
    .map(|g| pose(g))
    .collect()
}

pub fn art() -> Art {
    let start = pose(&STAND);
    Art {
        width: 24,
        height: 12,
        start,
        idle: idle_cycle(),
        rest_frames: vec![5, 8, 17],
        work: work_cycle(),
        // A thought bubble over the thorax: the ant holds still and wonders.
        waiting_mark: [(10, 0), (12, 0), (11, 1)].into_iter().collect(),
        // The crumb dropped, antennae drooping, head low.
        error: pose(&SULK),
        error_pulse: [(20, 7)].into_iter().collect(),
    }
}
